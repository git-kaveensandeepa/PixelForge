            }
            ElementType.ICON -> {
                sb.appendLine("$indent// ${element.name} [Icon: ${element.iconName}]")
                sb.appendLine("${indent}Icon(")
                sb.appendLine("$indent    imageVector = Icons.Default.Star,")
                sb.appendLine("$indent    contentDescription = \"${escapeString(element.name)}\",")
                sb.appendLine("$indent    tint = Color($textCol),")
                sb.appendLine("$indent    modifier = Modifier")
                sb.appendLine("$indent        .offset(x = ${element.x.toInt()}.dp, y = ${element.y.toInt()}.dp)")
                sb.appendLine("$indent        .size(width = ${element.width.toInt()}.dp, height = ${element.height.toInt()}.dp)")
                sb.appendLine("$indent)")
            }
            ElementType.TEXT_FIELD -> {
                sb.appendLine("$indent// ${element.name} [Input Field]")
                sb.appendLine("${indent}OutlinedTextField(")
                sb.appendLine("$indent    value = \"${escapeString(element.text)}\",")
                sb.appendLine("$indent    onValueChange = { /* onTextChange */ },")
                sb.appendLine("$indent    placeholder = { Text(\"${escapeString(element.placeholder)}\") },")
                sb.appendLine("$indent    shape = RoundedCornerShape(${element.cornerRadius.toInt()}.dp),")
                sb.appendLine("$indent    modifier = Modifier")
                sb.appendLine("$indent        .offset(x = ${element.x.toInt()}.dp, y = ${element.y.toInt()}.dp)")
                sb.appendLine("$indent        .size(width = ${element.width.toInt()}.dp, height = ${element.height.toInt()}.dp)")
                sb.appendLine("$indent)")
            }
            ElementType.SWITCH -> {
                sb.appendLine("$indent// ${element.name} [Toggle Switch]")
                sb.appendLine("${indent}Switch(")
                sb.appendLine("$indent    checked = ${element.isChecked},")
                sb.appendLine("$indent    onCheckedChange = { /* onToggle */ },")
                sb.appendLine("$indent    modifier = Modifier")
                sb.appendLine("$indent        .offset(x = ${element.x.toInt()}.dp, y = ${element.y.toInt()}.dp)")
                sb.appendLine("$indent)")
            }
            ElementType.CHECKBOX -> {
                sb.appendLine("$indent// ${element.name} [Checkbox]")
                sb.appendLine("${indent}Row(")
                sb.appendLine("$indent    verticalAlignment = Alignment.CenterVertically,")
                sb.appendLine("$indent    modifier = Modifier")
                sb.appendLine("$indent        .offset(x = ${element.x.toInt()}.dp, y = ${element.y.toInt()}.dp)")
                sb.appendLine("$indent        .size(width = ${element.width.toInt()}.dp, height = ${element.height.toInt()}.dp)")
                sb.appendLine("$indent) {")
                sb.appendLine("$indent    Checkbox(checked = ${element.isChecked}, onCheckedChange = { /* onCheck */ })")
                sb.appendLine("$indent    Text(text = \"${escapeString(element.text)}\", color = Color($textCol), fontSize = ${element.fontSize.toInt()}.sp)")
                sb.appendLine("$indent}")
            }
        }
        return sb.toString()
    }

    fun generateSvg(artboard: Artboard): String {
        val sb = StringBuilder()
        sb.appendLine("<?xml version=\"1.0\" encoding=\"UTF-8\"?>")
        sb.appendLine("<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"${artboard.width}\" height=\"${artboard.height}\" viewBox=\"0 0 ${artboard.width} ${artboard.height}\">")
        sb.appendLine("  <!-- Artboard Background -->")
        sb.appendLine("  <rect width=\"100%\" height=\"100%\" fill=\"${artboard.backgroundColorHex}\"/>")

        for (elem in artboard.elements) {
            if (!elem.isVisible) continue
            val opacityAttr = if (elem.opacity < 1f) " opacity=\"${elem.opacity}\"" else ""
            val transformAttr = if (elem.rotation != 0f) " transform=\"rotate(${elem.rotation} ${elem.x + elem.width / 2} ${elem.y + elem.height / 2})\"" else ""

            when (elem.type) {
                ElementType.RECTANGLE -> {
                    val rxAttr = if (elem.cornerRadius > 0) " rx=\"${elem.cornerRadius}\" ry=\"${elem.cornerRadius}\"" else ""
                    val strokeAttr = if (elem.strokeWidth > 0) " stroke=\"${elem.strokeColorHex}\" stroke-width=\"${elem.strokeWidth}\"" else ""
                    sb.appendLine("  <rect x=\"${elem.x}\" y=\"${elem.y}\" width=\"${elem.width}\" height=\"${elem.height}\" fill=\"${elem.fillColorHex}\"$rxAttr$strokeAttr$opacityAttr$transformAttr/>")
                }
                ElementType.CIRCLE -> {
                    val cx = elem.x + elem.width / 2f
                    val cy = elem.y + elem.height / 2f
                    val r = minOf(elem.width, elem.height) / 2f
                    sb.appendLine("  <circle cx=\"$cx\" cy=\"$cy\" r=\"$r\" fill=\"${elem.fillColorHex}\"$opacityAttr$transformAttr/>")
                }
                ElementType.LINE -> {
                    val strokeCol = if (elem.strokeWidth > 0) elem.strokeColorHex else elem.fillColorHex
                    val strokeW = if (elem.strokeWidth > 0) elem.strokeWidth else elem.height.coerceAtLeast(1f)
                    sb.appendLine("  <line x1=\"${elem.x}\" y1=\"${elem.y}\" x2=\"${elem.x + elem.width}\" y2=\"${elem.y}\" stroke=\"$strokeCol\" stroke-width=\"$strokeW\"$opacityAttr$transformAttr/>")
                }
                ElementType.BUTTON -> {
                    val rxAttr = if (elem.cornerRadius > 0) " rx=\"${elem.cornerRadius}\" ry=\"${elem.cornerRadius}\"" else ""
                    sb.appendLine("  <g$transformAttr$opacityAttr>")
                    sb.appendLine("    <rect x=\"${elem.x}\" y=\"${elem.y}\" width=\"${elem.width}\" height=\"${elem.height}\" fill=\"${elem.fillColorHex}\"$rxAttr/>")
                    val cx = elem.x + elem.width / 2f
                    val cy = elem.y + elem.height / 2f + (elem.fontSize / 3f)
                    sb.appendLine("    <text x=\"$cx\" y=\"$cy\" fill=\"${elem.textColorHex}\" font-size=\"${elem.fontSize}\" font-family=\"system-ui, sans-serif\" text-anchor=\"middle\" font-weight=\"bold\">${escapeXml(elem.text)}</text>")
                    sb.appendLine("  </g>")
                }
                ElementType.TEXT -> {
                    val anchor = when (elem.textAlign) {
                        TextAlignOption.LEFT -> "start"
                        TextAlignOption.CENTER -> "middle"
                        TextAlignOption.RIGHT -> "end"
                    }
                    val textX = when (elem.textAlign) {
                        TextAlignOption.LEFT -> elem.x + 4f
                        TextAlignOption.CENTER -> elem.x + elem.width / 2f
                        TextAlignOption.RIGHT -> elem.x + elem.width - 4f
                    }
                    val textY = elem.y + elem.fontSize
                    val weight = if (elem.isBold) " font-weight=\"bold\"" else ""
                    val style = if (elem.isItalic) " font-style=\"italic\"" else ""
                    sb.appendLine("  <text x=\"$textX\" y=\"$textY\" fill=\"${elem.textColorHex}\" font-size=\"${elem.fontSize}\" font-family=\"system-ui, sans-serif\" text-anchor=\"$anchor\"$weight$style$opacityAttr$transformAttr>${escapeXml(elem.text)}</text>")
                }
                ElementType.IMAGE_PLACEHOLDER -> {
                    val rxAttr = if (elem.cornerRadius > 0) " rx=\"${elem.cornerRadius}\" ry=\"${elem.cornerRadius}\"" else ""
                    sb.appendLine("  <g$transformAttr$opacityAttr>")
                    sb.appendLine("    <rect x=\"${elem.x}\" y=\"${elem.y}\" width=\"${elem.width}\" height=\"${elem.height}\" fill=\"${elem.fillColorHex}\"$rxAttr/>")
                    val cx = elem.x + elem.width / 2f
                    val cy = elem.y + elem.height / 2f
                    sb.appendLine("    <text x=\"$cx\" y=\"$cy\" fill=\"${elem.textColorHex}\" font-size=\"12\" font-family=\"system-ui, sans-serif\" text-anchor=\"middle\">Image [Placeholder]</text>")
                    sb.appendLine("  </g>")
                }
                ElementType.ICON -> {
                    sb.appendLine("  <g$transformAttr$opacityAttr>")
                    val rxAttr = if (elem.cornerRadius > 0) " rx=\"${elem.cornerRadius}\"" else ""
                    if (elem.fillColorHex != "#00000000" && !elem.fillColorHex.uppercase().startsWith("#00")) {
                        sb.appendLine("    <rect x=\"${elem.x}\" y=\"${elem.y}\" width=\"${elem.width}\" height=\"${elem.height}\" fill=\"${elem.fillColorHex}\"$rxAttr/>")
                    }
                    val cx = elem.x + elem.width / 2f
                    val cy = elem.y + elem.height / 2f + 5
                    sb.appendLine("    <text x=\"$cx\" y=\"$cy\" fill=\"${elem.textColorHex}\" font-size=\"16\" font-family=\"system-ui, sans-serif\" text-anchor=\"middle\">★ ${escapeXml(elem.iconName)}</text>")
                    sb.appendLine("  </g>")
                }
                ElementType.TEXT_FIELD -> {
                    val rxAttr = if (elem.cornerRadius > 0) " rx=\"${elem.cornerRadius}\"" else ""
                    val strokeCol = if (elem.strokeWidth > 0) elem.strokeColorHex else "#6366F1"
                    val strokeW = if (elem.strokeWidth > 0) elem.strokeWidth else 1.5f
                    sb.appendLine("  <g$transformAttr$opacityAttr>")
                    sb.appendLine("    <rect x=\"${elem.x}\" y=\"${elem.y}\" width=\"${elem.width}\" height=\"${elem.height}\" fill=\"${elem.fillColorHex}\" stroke=\"$strokeCol\" stroke-width=\"$strokeW\"$rxAttr/>")
                    val displayTxt = if (elem.text.isNotEmpty()) elem.text else elem.placeholder
                    sb.appendLine("    <text x=\"${elem.x + 12}\" y=\"${elem.y + elem.height / 2f + (elem.fontSize / 3f)}\" fill=\"${elem.textColorHex}\" font-size=\"${elem.fontSize}\" font-family=\"system-ui, sans-serif\">${escapeXml(displayTxt)}</text>")
                    sb.appendLine("  </g>")
                }
                ElementType.SWITCH -> {
                    val rx = elem.height / 2f
                    val trackCol = if (elem.isChecked) elem.fillColorHex else "#374151"
                    val thumbCol = if (elem.isChecked) elem.textColorHex else "#D1D5DB"
                    val thumbCx = if (elem.isChecked) elem.x + elem.width - rx else elem.x + rx
                    sb.appendLine("  <g$transformAttr$opacityAttr>")
                    sb.appendLine("    <rect x=\"${elem.x}\" y=\"${elem.y}\" width=\"${elem.width}\" height=\"${elem.height}\" fill=\"$trackCol\" rx=\"$rx\"/>")
                    sb.appendLine("    <circle cx=\"$thumbCx\" cy=\"${elem.y + rx}\" r=\"${(elem.height - 8f) / 2f}\" fill=\"$thumbCol\"/>")
                    sb.appendLine("  </g>")
                }
                ElementType.CHECKBOX -> {
                    val boxY = elem.y + (elem.height - 20f) / 2f
                    val boxFill = if (elem.isChecked) elem.fillColorHex else "none"
                    val boxStroke = if (elem.isChecked) elem.fillColorHex else elem.textColorHex
                    sb.appendLine("  <g$transformAttr$opacityAttr>")
                    sb.appendLine("    <rect x=\"${elem.x}\" y=\"$boxY\" width=\"20\" height=\"20\" fill=\"$boxFill\" stroke=\"$boxStroke\" stroke-width=\"2\" rx=\"4\"/>")
                    if (elem.isChecked) {
                        sb.appendLine("    <text x=\"${elem.x + 10}\" y=\"${elem.y + (elem.height / 2f) + 5}\" fill=\"${elem.textColorHex}\" font-size=\"14\" text-anchor=\"middle\">✓</text>")
                    }
                    if (elem.text.isNotEmpty()) {
                        sb.appendLine("    <text x=\"${elem.x + 28}\" y=\"${elem.y + (elem.height / 2f) + (elem.fontSize / 3f)}\" fill=\"${elem.textColorHex}\" font-size=\"${elem.fontSize}\" font-family=\"system-ui, sans-serif\">${escapeXml(elem.text)}</text>")
                    }
                    sb.appendLine("  </g>")
                }
            }
        }
        sb.appendLine("</svg>")
        return sb.toString()
    }

    fun generateHtmlCss(artboard: Artboard): String {
        val sb = StringBuilder()
        sb.appendLine("<!DOCTYPE html>")
        sb.appendLine("<html lang=\"en\">")
        sb.appendLine("<head>")
        sb.appendLine("  <meta charset=\"UTF-8\">")
        sb.appendLine("  <title>${escapeXml(artboard.name)} - PixelForge Export</title>")
        sb.appendLine("  <style>")
        sb.appendLine("    :root {")
        sb.appendLine("      --artboard-width: ${artboard.width}px;")
        sb.appendLine("      --artboard-height: ${artboard.height}px;")
        sb.appendLine("      --artboard-bg: ${artboard.backgroundColorHex};")
        sb.appendLine("    }")
        sb.appendLine("    body {")
        sb.appendLine("      margin: 0; padding: 24px; background: #0B0C10;")
        sb.appendLine("      display: flex; justify-content: center; align-items: center;")
        sb.appendLine("      font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif;")
        sb.appendLine("    }")
        sb.appendLine("    .artboard {")
        sb.appendLine("      position: relative; width: var(--artboard-width); height: var(--artboard-height);")
        sb.appendLine("      background-color: var(--artboard-bg); border-radius: 24px; overflow: hidden;")
        sb.appendLine("      box-shadow: 0 20px 40px rgba(0,0,0,0.4);")
        sb.appendLine("    }")
        sb.appendLine("    .element { position: absolute; box-sizing: border-box; }")
        sb.appendLine("  </style>")
        sb.appendLine("</head>")
        sb.appendLine("<body>")
        sb.appendLine("  <div class=\"artboard\">")

        for (elem in artboard.elements) {
            if (!elem.isVisible) continue
            val style = StringBuilder()
            style.append("left: ${elem.x}px; top: ${elem.y}px; width: ${elem.width}px; height: ${elem.height}px; ")
            if (elem.rotation != 0f) style.append("transform: rotate(${elem.rotation}deg); ")
            if (elem.opacity < 1f) style.append("opacity: ${elem.opacity}; ")

            when (elem.type) {
                ElementType.RECTANGLE -> {
                    style.append("background-color: ${elem.fillColorHex}; ")
                    if (elem.cornerRadius > 0) style.append("border-radius: ${elem.cornerRadius}px; ")
                    if (elem.strokeWidth > 0) style.append("border: ${elem.strokeWidth}px solid ${elem.strokeColorHex}; ")
                    sb.appendLine("    <div class=\"element\" style=\"$style\"></div>")
                }
                ElementType.CIRCLE -> {
                    style.append("background-color: ${elem.fillColorHex}; border-radius: 50%; ")
                    sb.appendLine("    <div class=\"element\" style=\"$style\"></div>")
                }
                ElementType.LINE -> {
                    val lineCol = if (elem.strokeWidth > 0) elem.strokeColorHex else elem.fillColorHex
                    val lineH = if (elem.strokeWidth > 0) elem.strokeWidth else 2f
                    style.append("background-color: $lineCol; height: ${lineH}px; ")
                    sb.appendLine("    <div class=\"element\" style=\"$style\"></div>")
                }
                ElementType.BUTTON -> {
                    style.append("background-color: ${elem.fillColorHex}; color: ${elem.textColorHex}; ")
                    style.append("border: none; border-radius: ${elem.cornerRadius}px; font-size: ${elem.fontSize}px; ")
                    style.append("font-weight: ${if (elem.isBold) "bold" else "600"}; cursor: pointer; ")
                    style.append("display: flex; align-items: center; justify-content: center; ")
                    sb.appendLine("    <button class=\"element\" style=\"$style\">${escapeXml(elem.text)}</button>")
                }
                ElementType.TEXT -> {
                    style.append("color: ${elem.textColorHex}; font-size: ${elem.fontSize}px; ")
                    if (elem.isBold) style.append("font-weight: bold; ")
                    if (elem.isItalic) style.append("font-style: italic; ")
                    style.append("text-align: ${elem.textAlign.name.lowercase()}; ")
                    sb.appendLine("    <div class=\"element\" style=\"$style\">${escapeXml(elem.text)}</div>")
                }
                ElementType.IMAGE_PLACEHOLDER -> {
                    style.append("background-color: ${elem.fillColorHex}; border-radius: ${elem.cornerRadius}px; ")
                    style.append("display: flex; align-items: center; justify-content: center; color: ${elem.textColorHex}; font-size: 13px; ")
                    sb.appendLine("    <div class=\"element\" style=\"$style\">🖼 ${escapeXml(elem.name)}</div>")
                }
                ElementType.ICON -> {
                    style.append("display: flex; align-items: center; justify-content: center; color: ${elem.textColorHex}; font-size: 18px; ")
                    if (elem.fillColorHex != "#00000000" && !elem.fillColorHex.uppercase().startsWith("#00")) {
                        style.append("background-color: ${elem.fillColorHex}; border-radius: ${elem.cornerRadius}px; ")
                    }
                    sb.appendLine("    <div class=\"element\" style=\"$style\">★ ${escapeXml(elem.iconName)}</div>")
                }
                ElementType.TEXT_FIELD -> {
                    val strokeCol = if (elem.strokeWidth > 0) elem.strokeColorHex else "#6366F1"
                    val strokeW = if (elem.strokeWidth > 0) elem.strokeWidth else 1.5f
                    style.append("background-color: ${elem.fillColorHex}; border-radius: ${elem.cornerRadius}px; border: ${strokeW}px solid $strokeCol; ")
                    style.append("padding: 0 12px; display: flex; align-items: center; color: ${elem.textColorHex}; font-size: ${elem.fontSize}px; ")
                    val displayTxt = if (elem.text.isNotEmpty()) elem.text else elem.placeholder
                    sb.appendLine("    <div class=\"element\" style=\"$style\">${escapeXml(displayTxt)}</div>")
                }
                ElementType.SWITCH -> {
                    val trackBg = if (elem.isChecked) elem.fillColorHex else "#374151"
                    val thumbBg = if (elem.isChecked) elem.textColorHex else "#D1D5DB"
                    val thumbLeft = if (elem.isChecked) "calc(100% - ${elem.height - 4}px)" else "2px"
                    style.append("background-color: $trackBg; border-radius: ${elem.height / 2}px; padding: 2px; position: absolute; ")
                    sb.appendLine("    <div class=\"element\" style=\"$style\"><div style=\"position: absolute; left: $thumbLeft; top: 2px; width: ${elem.height - 4}px; height: ${elem.height - 4}px; border-radius: 50%; background-color: $thumbBg;\"></div></div>")
                }
                ElementType.CHECKBOX -> {
                    val boxBg = if (elem.isChecked) elem.fillColorHex else "transparent"
                    val boxBorder = if (elem.isChecked) elem.fillColorHex else elem.textColorHex
                    style.append("display: flex; align-items: center; gap: 8px; color: ${elem.textColorHex}; font-size: ${elem.fontSize}px; ")
                    val checkMark = if (elem.isChecked) "✓" else ""
                    sb.appendLine("    <div class=\"element\" style=\"$style\"><div style=\"width: 18px; height: 18px; border-radius: 4px; background: $boxBg; border: 2px solid $boxBorder; display: flex; align-items: center; justify-content: center; font-size: 12px;\">$checkMark</div><span>${escapeXml(elem.text)}</span></div>")
                }
            }
        }

        sb.appendLine("  </div>")
        sb.appendLine("</body>")
        sb.appendLine("</html>")
        return sb.toString()
    }

    fun generateDesignSpec(element: DesignElement, artboard: Artboard): String {
        val sb = StringBuilder()
        sb.appendLine("Element: ${element.name} (${element.type.name})")
        sb.appendLine("—".repeat(32))
        sb.appendLine("Position:   X = ${element.x.toInt()} dp, Y = ${element.y.toInt()} dp")
        sb.appendLine("Dimensions: W = ${element.width.toInt()} dp, H = ${element.height.toInt()} dp")
        sb.appendLine("Rotation:   ${element.rotation.toInt()}°")
        sb.appendLine("Fill Color: ${element.fillColorHex} (Opacity: ${(element.opacity * 100).toInt()}%)")
        if (element.strokeWidth > 0) {
            sb.appendLine("Border:     ${element.strokeWidth} dp solid ${element.strokeColorHex}")
        }
        if (element.cornerRadius > 0) {
            sb.appendLine("Radius:     ${element.cornerRadius} dp")
        }
        if (element.type == ElementType.TEXT || element.type == ElementType.BUTTON) {
            sb.appendLine("Content:    \"${element.text}\"")
            sb.appendLine("Typography: ${element.fontSize.toInt()} sp, ${if (element.isBold) "Bold" else "Regular"}, Align: ${element.textAlign}")
            sb.appendLine("Text Color: ${element.textColorHex}")
        }
        sb.appendLine("—".repeat(32))
        sb.appendLine("Margins to Artboard:")
        sb.appendLine("  Left:   ${element.x.toInt()} dp")
        sb.appendLine("  Top:    ${element.y.toInt()} dp")
        sb.appendLine("  Right:  ${(artboard.width - (element.x + element.width)).toInt()} dp")
        sb.appendLine("  Bottom: ${(artboard.height - (element.y + element.height)).toInt()} dp")
        return sb.toString()
    }

    private fun formatHexColor(hex: String): String {
        val clean = hex.removePrefix("#")
        return when (clean.length) {
            6 -> "0xFF$clean"
            8 -> "0x$clean"
            else -> "0xFF000000"
        }
    }

    private fun escapeString(s: String): String {
        return s.replace("\\", "\\\\").replace("\"", "\\\"").replace("\n", "\\n")
    }

    private fun escapeXml(s: String): String {
        return s.replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;")
            .replace("\"", "&quot;")
            .replace("'", "&apos;")
    }
