                sb.appendLine("$indent        fontSize = ${element.fontSize.toInt()}.sp,")
                sb.appendLine("$indent        fontWeight = ${if (element.isBold) "FontWeight.Bold" else "FontWeight.SemiBold"}")
                sb.appendLine("$indent    )")
                sb.appendLine("$indent}")
            }
            ElementType.IMAGE_PLACEHOLDER -> {
                sb.appendLine("$indent// ${element.name} [Image Container]")
                sb.appendLine("${indent}Surface(")
                sb.appendLine("$indent    shape = RoundedCornerShape(${element.cornerRadius.toInt()}.dp),")
