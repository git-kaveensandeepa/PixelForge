    fun generateJetpackComposeCode(artboard: Artboard): String {
        val funName = artboard.name.replace("[^a-zA-Z0-9]".toRegex(), "")
            .replaceFirstChar { it.uppercase() }
            .ifBlank { "ScreenView" }

        val sb = StringBuilder()
        sb.appendLine("// Generated by PixelForge Pro — Offline Native UI Design Studio")
        sb.appendLine("package com.example.ui.generated")
        sb.appendLine()
        sb.appendLine("import androidx.compose.foundation.background")
        sb.appendLine("import androidx.compose.foundation.border")
        sb.appendLine("import androidx.compose.foundation.layout.*")
        sb.appendLine("import androidx.compose.foundation.shape.CircleShape")
        sb.appendLine("import androidx.compose.foundation.shape.RoundedCornerShape")
        sb.appendLine("import androidx.compose.material3.*")
        sb.appendLine("import androidx.compose.runtime.Composable")
        sb.appendLine("import androidx.compose.ui.Alignment")
        sb.appendLine("import androidx.compose.ui.Modifier")
        sb.appendLine("import androidx.compose.ui.draw.clip")
        sb.appendLine("import androidx.compose.ui.graphics.Color")
        sb.appendLine("import androidx.compose.ui.text.font.FontStyle")
        sb.appendLine("import androidx.compose.ui.text.font.FontWeight")
        sb.appendLine("import androidx.compose.ui.text.style.TextAlign")
        sb.appendLine("import androidx.compose.ui.unit.dp")
        sb.appendLine("import androidx.compose.ui.unit.sp")
        sb.appendLine()
        sb.appendLine("@Composable")
        sb.appendLine("fun $funName() {")
        sb.appendLine("    Box(")
        sb.appendLine("        modifier = Modifier")
        sb.appendLine("            .size(width = ${artboard.width.toInt()}.dp, height = ${artboard.height.toInt()}.dp)")
        sb.appendLine("            .background(Color(${formatHexColor(artboard.backgroundColorHex)}))")
        sb.appendLine("    ) {")

        for (element in artboard.elements) {
            if (!element.isVisible) continue
            sb.appendLine(generateElementComposeCode(element, "        "))
        }

        sb.appendLine("    }")
        sb.appendLine("}")
        return sb.toString()
    }

    private fun generateElementComposeCode(element: DesignElement, indent: String): String {
        val sb = StringBuilder()
        val fill = formatHexColor(element.fillColorHex)
        val textCol = formatHexColor(element.textColorHex)

        when (element.type) {
            ElementType.RECTANGLE -> {
                sb.appendLine("$indent// ${element.name}")
                sb.appendLine("${indent}Box(")
                sb.appendLine("$indent    modifier = Modifier")
                sb.appendLine("$indent        .offset(x = ${element.x.toInt()}.dp, y = ${element.y.toInt()}.dp)")
                sb.appendLine("$indent        .size(width = ${element.width.toInt()}.dp, height = ${element.height.toInt()}.dp)")
                if (element.cornerRadius > 0) {
                    sb.appendLine("$indent        .clip(RoundedCornerShape(${element.cornerRadius.toInt()}.dp))")
                }
                sb.appendLine("$indent        .background(Color($fill).copy(alpha = ${element.opacity}f))")
                if (element.strokeWidth > 0) {
                    val strokeCol = formatHexColor(element.strokeColorHex)
                    val shape = if (element.cornerRadius > 0) "RoundedCornerShape(${element.cornerRadius.toInt()}.dp)" else "RoundedCornerShape(0.dp)"
                    sb.appendLine("$indent        .border(${element.strokeWidth.toInt()}.dp, Color($strokeCol), $shape)")
                }
                sb.appendLine("$indent)")
            }
            ElementType.CIRCLE -> {
                sb.appendLine("$indent// ${element.name}")
                sb.appendLine("${indent}Box(")
                sb.appendLine("$indent    modifier = Modifier")
                sb.appendLine("$indent        .offset(x = ${element.x.toInt()}.dp, y = ${element.y.toInt()}.dp)")
                sb.appendLine("$indent        .size(width = ${element.width.toInt()}.dp, height = ${element.height.toInt()}.dp)")
                sb.appendLine("$indent        .clip(CircleShape)")
                sb.appendLine("$indent        .background(Color($fill).copy(alpha = ${element.opacity}f))")
                sb.appendLine("$indent)")
            }
            ElementType.LINE -> {
                sb.appendLine("$indent// ${element.name}")
                val strokeCol = formatHexColor(if (element.strokeWidth > 0) element.strokeColorHex else element.fillColorHex)
                val lineH = if (element.strokeWidth > 0) element.strokeWidth.toInt() else element.height.toInt().coerceAtLeast(1)
                sb.appendLine("${indent}HorizontalDivider(")
                sb.appendLine("$indent    modifier = Modifier")
                sb.appendLine("$indent        .offset(x = ${element.x.toInt()}.dp, y = ${element.y.toInt()}.dp)")
                sb.appendLine("$indent        .width(${element.width.toInt()}.dp),")
                sb.appendLine("$indent    thickness = ${lineH}.dp,")
                sb.appendLine("$indent    color = Color($strokeCol)")
                sb.appendLine("$indent)")
