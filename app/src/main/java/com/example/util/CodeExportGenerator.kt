                sb.appendLine("$indent// ${element.name}")
                sb.appendLine("${indent}Text(")
                sb.appendLine("$indent    text = \"${escapeString(element.text)}\",")
                sb.appendLine("$indent    color = Color($textCol),")
                sb.appendLine("$indent    fontSize = ${element.fontSize.toInt()}.sp,")
                sb.appendLine("$indent    fontWeight = $weight,")
                sb.appendLine("$indent    fontStyle = $style,")
                sb.appendLine("$indent    textAlign = $align,")
                sb.appendLine("$indent    modifier = Modifier")
                sb.appendLine("$indent        .offset(x = ${element.x.toInt()}.dp, y = ${element.y.toInt()}.dp)")
                sb.appendLine("$indent        .width(${element.width.toInt()}.dp)")
                sb.appendLine("$indent)")
            }
            ElementType.BUTTON -> {
                sb.appendLine("$indent// ${element.name}")
                sb.appendLine("${indent}Button(")
                sb.appendLine("$indent    onClick = { /* Action */ },")
